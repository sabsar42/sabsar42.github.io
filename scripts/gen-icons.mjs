/**
 * Copies just the brand icons the site uses from simple-icons (CC0) into lib/brand-icons.ts,
 * so the full icon set never reaches the bundle. Run: npm run icons
 */
import fs from "node:fs";
import * as si from "simple-icons";

const SLUGS = [
  // stack
  "langgraph", "langchain", "modelcontextprotocol", "claude", "pytorch", "tensorflow", "huggingface", "scikitlearn",
  "opencv", "python", "typescript", "postgresql", "fastapi", "nodedotjs", "nextdotjs", "supabase", "docker", "vercel",
  "flutter", "googlegemini", "resend", "firebase", "tailwindcss", "react", "dart",
  // profiles
  "github", "kaggle", "googlescholar", "researchgate", "youtube", "openrouter",
];

const bySlug = new Map(Object.values(si).filter((x) => x && x.slug).map((x) => [x.slug, x]));
const out = {};
for (const s of SLUGS) {
  const icon = bySlug.get(s);
  if (!icon) throw new Error(`simple-icons has no "${s}"`);
  out[s] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}
// LinkedIn is not in simple-icons; this is the standard "in" mark.
out.linkedin = {
  title: "LinkedIn",
  hex: "#0A66C2",
  path: "M20.45 20.45h-3.56v-5.57c0-1.33-.02-3.04-1.85-3.04-1.85 0-2.14 1.45-2.14 2.94v5.67H9.35V9h3.41v1.56h.05c.48-.9 1.64-1.85 3.37-1.85 3.6 0 4.27 2.37 4.27 5.46v6.28zM5.34 7.43a2.06 2.06 0 1 1 0-4.13 2.06 2.06 0 0 1 0 4.13zM7.12 20.45H3.56V9h3.56v11.45zM22.22 0H1.77C.79 0 0 .77 0 1.73v20.54C0 23.23.79 24 1.77 24h20.45c.98 0 1.78-.77 1.78-1.73V1.73C24 .77 23.2 0 22.22 0z",
};

const body = `/* Generated by scripts/gen-icons.mjs from simple-icons (CC0). Do not edit by hand. */
export type BrandIconData = { title: string; hex: string; path: string };
export const BRAND_ICONS = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, BrandIconData>;
export type BrandSlug = keyof typeof BRAND_ICONS;
`;
fs.writeFileSync("lib/brand-icons.ts", body);
console.log(`wrote ${Object.keys(out).length} icons`);
